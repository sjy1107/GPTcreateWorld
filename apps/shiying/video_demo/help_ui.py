"""Help stays inside the app: short hover hints and readable step dialogs."""
from html import escape
from PySide6.QtGui import QTextBlockFormat, QTextCursor
from PySide6.QtWidgets import QDialog, QDialogButtonBox, QPushButton, QTextBrowser, QVBoxLayout


def run_dialog(dialog):
    try:
        return dialog.exec()
    finally:
        # A parent-owned Qt window otherwise stays alive after exec() returns.
        dialog.deleteLater()


def set_help_content(browser, text):
    browser.setStyleSheet("QTextBrowser {background: white; font-size: 14px; border: 1px solid #dce3ef; border-radius: 8px; padding: 12px;}")
    browser.setMarkdown(text)
    block = browser.document().begin()
    while block.isValid():
        cursor = QTextCursor(block)
        formatting = cursor.blockFormat()
        formatting.setBottomMargin(8)
        formatting.setLineHeight(140, QTextBlockFormat.LineHeightTypes.ProportionalHeight.value)
        cursor.setBlockFormat(formatting)
        block = block.next()


def help_button(title, text, callback=None):
    button = QPushButton("?")
    button.setObjectName("helpButton")
    button.setFixedSize(28, 28)
    button.setAccessibleName(title)
    button.setToolTip(f'<qt><b>{escape(title)}</b><br>{escape(text).replace(chr(10), "<br>")}</qt>')
    button.setToolTipDuration(15000)
    if callback:
        button.clicked.connect(callback)
    return button


class HelpDialog(QDialog):
    def __init__(self, title, text, parent=None):
        super().__init__(parent)
        self.setWindowTitle(title)
        self.resize(720, 570)
        layout = QVBoxLayout(self)
        self.content = QTextBrowser()
        self.content.setOpenExternalLinks(True)
        set_help_content(self.content, text)
        layout.addWidget(self.content)
        buttons = QDialogButtonBox(QDialogButtonBox.StandardButton.Close)
        buttons.rejected.connect(self.reject)
        layout.addWidget(buttons)


